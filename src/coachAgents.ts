export function coachOfId(id: CoachId | string | undefined | null): CoachAgent {
  return COACH_AGENTS.find((c) => c.id === id) ?? COACH_AGENTS[0]
}

export function isCoachId(s: string): s is CoachId {
  return COACH_AGENTS.some((c) => c.id === s)
}


export function buildCoachSystem(input: {
  coachId: CoachId
  bossName: string
  bossGender?: BossGender | string
  hostWho?: string
}): string {
  const agent = coachOfId(input.coachId)
  const name = (input.bossName || '').trim() || '哥哥'
  const gender = input.bossGender === '女' || input.bossGender === '未知' ? input.bossGender : '男'
  const who = (input.hostWho || '').trim() || agent.hostWhoFixed
  const relation = [
    `【本局关系】老板名称：${name}`,
    `老板性别：${gender}`,
    `主播自称/人设：${who}`,
  ].join('\n')
  return `${agent.systemPrompt}\n\n${COACH_WORLDBOOK}\n\n${relation}`
}

export interface CoachReplyItem {
  line: string
  purpose: string
}

export interface CoachParsed {
  analysis: string
  replies: CoachReplyItem[]
  note: string
  rawText: string
}

/** Best-effort parse of 【分析】/【回复N】/【注意】 plain text. */
export function parseCoachOutput(raw: string): CoachParsed {
  const text = (raw || '').replace(/\r\n/g, '\n').trim()
  const empty: CoachParsed = { analysis: '', replies: [], note: '', rawText: text }

  if (!text) return empty

  const analysisMatch = text.match(/【分析】\s*([\s\S]*?)(?=\n【回复\d】|\n【注意】|$)/)
  const noteMatch = text.match(/【注意】\s*([\s\S]*?)$/)
  const analysis = (analysisMatch?.[1] || '').trim()
  const note = (noteMatch?.[1] || '').trim()

  const replies: CoachReplyItem[] = []
  const replyRe = /【回复([123])】\s*([\s\S]*?)(?=\n【回复[123]】|\n【注意】|$)/g
  let m: RegExpExecArray | null
  while ((m = replyRe.exec(text))) {
    const block = (m[2] || '').trim()
    if (!block) continue
    const purposeMatch = block.match(/（目的[:：]\s*([^）]+)）/)
    const purpose = purposeMatch ? purposeMatch[1].trim() : ''
    let line = block
      .replace(/（目的[:：][^）]*）/g, '')
      .replace(/^\s*\n+|\n+\s*$/g, '')
      .trim()
    // drop leading label leftovers
    line = line.replace(/^（可直接复制的完整句子）\s*/u, '').trim()
    if (!line && purpose) line = purpose
    if (!line) continue
    replies.push({ line, purpose: purpose || '可直接复制发出' })
  }

  // Fallback: if markers missing but looks usable, keep raw in analysis
  if (!analysis && !replies.length) {
    if (/【回复1】/.test(text)) {
      return { analysis: text, replies: [], note: '', rawText: text }
    }
    return { ...empty, analysis: text }
  }

  return { analysis: analysis || '—', replies, note, rawText: text }
}
