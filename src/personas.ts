export function migratePersona(raw: string | null | undefined): PersonaId | null {
  if (!raw) return null
  const id = LEGACY[raw]
  if (!id) return null
  if (raw !== id) {
    try {
      localStorage.setItem(PERSONA_KEY, id)
    } catch {
      /* ignore quota / private mode */
    }
  }
  return id
}
